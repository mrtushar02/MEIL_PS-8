/**
 * 4. Generic Fallback PDF Generator
 */
export function downloadGenericPDF({ title, filename, lines = [], details = {} }) {
  const doc = new jsPDF('p', 'mm', 'a4');
  const cleanName = filename ? (filename.toLowerCase().endsWith('.pdf') ? filename : `${filename}.pdf`) : 'MEIL_Document.pdf';

  drawMeilHeader(doc, title || 'MEIL STATUTORY ESG RECORD', 'Official Verification Export');

  let y = 55;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(15, 23, 42);

  lines.forEach(line => {
    if (y > 260) {
      doc.addPage();
      drawMeilHeader(doc, title, 'Continuation Page');
      y = 55;
    }
    const split = doc.splitTextToSize(line, 182);
    doc.text(split, 14, y);
    y += (split.length * 5) + 2;
  });

  drawMeilFooter(doc, details.sha256 || null);
  doc.save(cleanName);
}

// Helper to draw Footer
function drawMeilFooter(doc, sha256) {
  const pageHeight = doc.internal.pageSize.getHeight();
  
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.5);
  doc.line(14, pageHeight - 18, 196, pageHeight - 18);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(100, 116, 139);
  doc.text('Confidential · For Internal Statutory Audit & SEBI BRSR Reporting Only · Generated by MEIL ESG Enterprise System', 14, pageHeight - 12);

  if (sha256) {
    const truncated = sha256.length > 40 ? sha256.substring(0, 38) + '...' : sha256;
    doc.setFont('courier', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(71, 85, 105);
    doc.text(`SHA-256 SEAL: ${truncated}`, 14, pageHeight - 7);
  }

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7.5);
  doc.setTextColor(22, 163, 74);
  doc.text('✓ ICAI Guideline 2024 Audit Traceable', 150, pageHeight - 7);
}

